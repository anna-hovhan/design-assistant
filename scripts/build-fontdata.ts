// Dev-time script: turns font files into glyph outlines so generators stay dependency-free and draw text as paths.
// Run with: npm run build:fonts   (writes src/generators/architecture/fontdata.ts)
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import opentype from "opentype.js";

const require = createRequire(import.meta.url);
const FONTS: Record<string, string> = {
  manrope500: "@fontsource/manrope/files/manrope-latin-500-normal.woff",
  manrope700: "@fontsource/manrope/files/manrope-latin-700-normal.woff",
  syne700: "@fontsource/syne/files/syne-latin-700-normal.woff",
};
// Printable ASCII plus the few typographic characters the templates use.
const CHARS = [...Array.from({ length: 95 }, (_, i) => String.fromCharCode(32 + i)), "·", "—", "–", "→", "•", "’", "“", "”"];

const round = (n: number) => Math.round(n * 10) / 10;
const toPath = (path: opentype.Path) =>
  path.commands.map((c) => {
    switch (c.type) {
      case "M": case "L": return `${c.type}${round(c.x)} ${round(c.y)}`;
      case "Q": return `Q${round(c.x1)} ${round(c.y1)} ${round(c.x)} ${round(c.y)}`;
      case "C": return `C${round(c.x1)} ${round(c.y1)} ${round(c.x2)} ${round(c.y2)} ${round(c.x)} ${round(c.y)}`;
      default: return "Z";
    }
  }).join("");

let out = `// Generated by scripts/build-fontdata.ts. Do not edit.
// Glyph outlines of Manrope (500, 700) and Syne (700), SIL OFL, on a 1000-unit em with y pointing down (SVG space).
export type Glyphs = Record<string, [advance: number, path: string]>;
export const FONTDATA: Record<string, Glyphs> = {
`;
for (const [name, file] of Object.entries(FONTS)) {
  const font = opentype.parse(readFileSync(require.resolve(file)).buffer.slice(0) as ArrayBuffer);
  const scale = 1000 / font.unitsPerEm;
  const rows = CHARS.flatMap((ch) => {
    const glyph = font.charToGlyph(ch);
    if (glyph.index === 0 && ch !== " ") return [];
    const d = toPath(glyph.getPath(0, 0, 1000));
    return [`  ${JSON.stringify(ch)}: [${round((glyph.advanceWidth ?? 0) * scale)}, ${JSON.stringify(d)}],`];
  });
  out += ` ${name}: {\n${rows.join("\n")}\n },\n`;
}
out += "};\n";
writeFileSync("src/generators/architecture/fontdata.ts", out);
console.log(`wrote fontdata.ts (${(out.length / 1024).toFixed(0)} KB)`);
